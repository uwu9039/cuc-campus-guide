ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "sources"


def squash(s: str) -> str:
    return re.sub(r"\s+", "", s or "")


TEXTS: dict[str, str] = {}
for f in SRC.glob("*.txt"):
    TEXTS[f.stem] = squash(f.read_text(encoding="utf-8", errors="ignore"))
for sub in ("wendao-text", "great", "local", "huibian", "crawl", "cdp", "extra", "wechat", "pdf"):
    d = SRC / sub
    if not d.exists():
        continue
    for f in d.glob("*.txt"):
        TEXTS[f.stem] = squash(f.read_text(encoding="utf-8", errors="ignore"))


def q(src: str, text: str) -> dict[str, str]:
    assert squash(text) in TEXTS.get(src, ""), f"{src} 找不到：{text[:60]}"
    return {"src": src, "quote": text}


def build(iid, title, aliases, keywords, dept, steps, pitfalls, sources,
          confidence="high", answer=None, note=None, location=None, contact=None):
    ev: dict[str, dict] = {}
    out_steps = []
    for i, (src, what, when) in enumerate(steps):
        ev[f"steps.{i}"] = q(src, what)
        out_steps.append({"when": when, "what": what})
    out_pf = []
    for i, (src, what) in enumerate(pitfalls):
        ev[f"pitfalls.{i}"] = q(src, what)
        out_pf.append(what)
    answer_text = None
    if answer:
        ev["answer"] = q(*answer)
        answer_text = answer[1]
    location_text = None
    if location:
        ev["location"] = q(*location)
        location_text = location[1]
    contact_text = None
    if contact:
        ev["contact"] = q(*contact)
        contact_text = contact[1]
    return {
        "id": iid, "title": title, "aliases": aliases, "keywords": keywords,
        "dept": dept, "channel": ["线上系统"], "audience": ["本科生", "研究生"],
        "status": "verified", "confidence": confidence, "materials": [],
        "steps": out_steps, "fee": None, "location": location_text, "hours": None,
        "duration": None, "window": None, "pitfalls": out_pf, "contact": contact_text,
        "slots": [], "draft": None, "answer": answer_text, "kind": "service",
        "note": note, "source": sources, "evidence": ev,
    }


