def squash(s: str) -> str:
    return re.sub(r"\s+", "", s or "")


def load(src: str) -> str:
    for sub in SRC_DIRS:
        p = ROOT / "sources" / sub / f"{src}.txt"
        if p.exists():
            return squash(p.read_text(encoding="utf-8"))
    raise SystemExit(f"找不到原文：{src}")


