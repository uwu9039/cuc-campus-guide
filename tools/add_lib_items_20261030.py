def squash(s: str) -> str:
    return re.sub(r"\s+", "", s or "")


TEXTS: dict[str, str] = {}
for sub in ("", "wechat", "crawl", "cdp", "pdf", "chsi", "moe", "national", "extra",
            "huibian", "local", "wendao-extra", "wendao-text", "attachments/text",
            "ilib-text"):
    for p in (SRC / sub).glob("*.txt"):
        TEXTS[p.stem] = squash(p.read_text(encoding="utf-8", errors="ignore"))

META: dict[str, dict] = {}
for idx in sorted(SRC.glob("*-index.json")):
    try:
        rows = json.loads(idx.read_text(encoding="utf-8"))
    except Exception:
        continue
    if not isinstance(rows, dict):
        continue
    for slug, meta in rows.items():
        if isinstance(meta, dict) and meta.get("title"):
            META.setdefault(str(slug), meta)


def stem_of(prefix: str) -> str:
    hits = [k for k in INDEX if k.startswith(prefix)]
    if len(hits) != 1:
        raise SystemExit(f"索引里找不到唯一的「{prefix}」：{hits}")
    return hits[0]


def source(stem: str) -> dict:
    meta = META.get(stem) or {}
    return {"title": meta.get("title") or stem, "url": meta.get("url") or "", "checked": CHECKED}


def ev(*pairs: tuple[str, str]) -> dict:
    rows = [{"src": s, "quote": q} for s, q in pairs]
    return rows[0] if len(rows) == 1 else {"sources": rows}


def build(raw: dict, base_steps: int = 0, base_pitfalls: int = 0) -> dict:
    """把 (when, what, [(src, quote)]) 展开成 steps + evidence。"""
    item = json.loads(json.dumps(raw, ensure_ascii=False))
    steps, evidence = [], {}
    for i, (when, what, pairs) in enumerate(item.pop("steps")):
        steps.append({"when": when, "what": what})
        evidence[f"steps.{base_steps + i}"] = ev(*pairs)
    for i, (text, pairs) in enumerate(item.pop("pitfalls")):
        item.setdefault("pitfalls", []).append(text)
        evidence[f"pitfalls.{base_pitfalls + i}"] = ev(*pairs)
    for field in ("fee", "location", "hours", "contact"):
        if item.get(field):
            pairs = item.pop(f"{field}_ev")
            evidence[field] = ev(*pairs)
    item["steps"] = steps
    item["evidence"] = evidence
    stems = {one["src"] for rows in evidence.values()
             for one in (rows.get("sources") or [rows])}
    item["source"] = [source(s) for s in sorted(stems)]
    return item


