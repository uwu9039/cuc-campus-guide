def insert_steps(item: dict, at: int, rows: list[dict]) -> None:
    old = item.get("steps") or []
    ev_map = item.get("evidence") or {}
    shifted = {}
    for key, val in ev_map.items():
        if key.startswith("steps."):
            n = int(key.split(".")[1])
            shifted[f"steps.{n + len(rows) if n >= at else n}"] = val
        else:
            shifted[key] = val
    item["steps"] = old[:at] + rows + old[at:]
    item["evidence"] = shifted


def add_tags(item: dict, index: int, tags: list[str]) -> None:
    step = item["steps"][index]
    step["tags"] = list(dict.fromkeys([*(step.get("tags") or []), *tags]))


