def merge(existing: dict, new: dict, append: bool) -> dict:
    item = dict(existing)
    aliases = list(dict.fromkeys([*(new.get("aliases") or []), *(existing.get("aliases") or [])]))
    old_steps = existing.get("steps") or []
    old_pits = existing.get("pitfalls") or []
    old_ev = existing.get("evidence") or {}
    old_src = existing.get("source") or []
    item.update(new)
    item["aliases"] = aliases
    if append:
        seen = {squash(s.get("what")) for s in old_steps}
        item["steps"] = old_steps + [s for s in new["steps"] if squash(s["what"]) not in seen]
        pits = list(old_pits)
        for p in new["pitfalls"]:
            if p not in pits:
                pits.append(p)
        item["pitfalls"] = pits
        item["evidence"] = {**old_ev, **new["evidence"]}
        keys = {s.get("url") or s.get("title") for s in old_src}
        item["source"] = old_src + [s for s in new["source"] if (s.get("url") or s.get("title")) not in keys]
    return item


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="只校验引文，不写文件")
    args = ap.parse_args()

    path = ROOT / "items.json"
    data = json.loads(path.read_text(encoding="utf-8"))
    by_id = {i["id"]: i for i in data["items"]}

    bad: list[str] = []
    prepared: list[tuple[dict, bool]] = []
    for raw in ITEMS:
        raw = json.loads(json.dumps(raw, ensure_ascii=False))
        old = by_id.get(raw["id"])
        append = bool(raw.pop("append", False)) and bool(old)
        base_s = len((old or {}).get("steps") or []) if append else 0
        base_p = len((old or {}).get("pitfalls") or []) if append else 0
        item = build(raw, base_s, base_p)
        for field, evd in item["evidence"].items():
            for one in (evd.get("sources") or [evd]):
                src, quote = one["src"], squash(one["quote"])
                if src not in TEXTS:
                    bad.append(f"{item['id']} {field} 来源不存在 {src}")
                elif quote not in TEXTS[src]:
                    bad.append(f"{item['id']} {field} 原文找不到：{one['quote'][:40]}")
        prepared.append((item, append))

    if bad:
        print(f"✗ 引文校验失败 {len(bad)} 条：")
        for b in bad:
            print("  -", b)
        raise SystemExit(1)
    print(f"✓ 引文校验通过（{len(prepared)} 条，{sum(len(i['evidence']) for i, _ in prepared)} 个事实）")
    if args.check:
        return

    added = updated = 0
    for item, append in prepared:
        old = by_id.get(item["id"])
        if old:
            merged = merge(old, item, append)
            old.clear()
            old.update(merged)
            updated += 1
        else:
            item.setdefault("status", "verified")
            item.setdefault("confidence", "high")
            item.setdefault("materials", [])
            item.setdefault("slots", [])
            item.setdefault("draft", None)
            item.setdefault("answer", None)
            item.setdefault("kind", "service")
            item.setdefault("fee", None)
            item.setdefault("location", None)
            item.setdefault("hours", None)
            item.setdefault("duration", None)
            item.setdefault("window", None)
            item.setdefault("contact", None)
            data["items"].append(item)
            by_id[item["id"]] = item
            added += 1
    data["updated"] = CHECKED
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"新增 {added} 条，更新 {updated} 条，总计 {len(data['items'])} 条")


