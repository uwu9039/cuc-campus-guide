def squash(s: str) -> str:
    return re.sub(r"\s+", "", s or "")


_CACHE: dict[str, str] = {}


def src_text(slug: str) -> str:
    if slug in _CACHE:
        return _CACHE[slug]
    cands = [SRC / f"{slug}.txt"]
    for sub in ("wechat", "crawl", "cdp", "pdf", "chsi", "moe", "national",
                "extra", "huibian", "local", "wendao-extra", "wendao-text"):
        cands.append(SRC / sub / f"{slug}.txt")
    for f in cands:
        if f.exists():
            _CACHE[slug] = squash(f.read_text(encoding="utf-8"))
            return _CACHE[slug]
    raise FileNotFoundError(slug)


def seg(slug: str, start: str, end: str | None = None) -> str:
    text = src_text(slug)
    a = text.index(squash(start))
    b = text.index(squash(end), a) + len(squash(end)) if end else a + len(squash(start))
    return text[a:b]


def ev(slug: str, start: str, end: str | None = None) -> dict:
    return {"src": slug, "quote": seg(slug, start, end)}


def build(item_id, title, aliases, steps, *, dept, kind="service", sources,
          fee=None, location=None, hours=None, duration=None, window=None,
          materials=None, pitfalls=None, contact=None, slots=None, keywords=None):
    out = {
        "id": item_id,
        "title": title,
        "aliases": aliases,
        "keywords": keywords or [],
        "dept": dept,
        "channel": ["线下", "线上"],
        "audience": ["本科生", "研究生"],
        "status": "verified",
        "confidence": "high",
        "materials": [{"name": m[0]} for m in (materials or [])],
        "steps": [{"when": w, "what": t, "where": loc} if loc else {"when": w, "what": t}
                  for (w, t, loc, _q) in steps],
        "fee": fee,
        "location": location,
        "hours": hours,
        "duration": duration,
        "window": window,
        "pitfalls": [p for p, _ in (pitfalls or [])],
        "contact": contact,
        "slots": slots or [],
        "draft": None,
        "answer": None,
        "kind": kind,
        "source": sources,
        "evidence": {},
    }
    for n, (w, t, loc, q) in enumerate(steps):
        out["evidence"][f"steps.{n}"] = q
    if out["materials"]:
        for n, (_, q) in enumerate(materials):
            out["evidence"][f"materials.{n}"] = q
    if fee:
        out["evidence"]["fee"] = fee[1] if isinstance(fee, tuple) else None
    if location:
        out["evidence"]["location"] = location[1] if isinstance(location, tuple) else None
    if hours:
        out["evidence"]["hours"] = hours[1] if isinstance(hours, tuple) else None
    if duration:
        out["evidence"]["duration"] = duration[1] if isinstance(duration, tuple) else None
    if window:
        out["evidence"]["window"] = window[1] if isinstance(window, tuple) else None
    for n, (_, q) in enumerate(pitfalls or []):
        out["evidence"][f"pitfalls.{n}"] = q
    # 值字段只留文本
    for k in ("fee", "location", "hours", "duration", "window"):
        if isinstance(out[k], tuple):
            out[k] = out[k][0]
    out["evidence"] = {k: v for k, v in out["evidence"].items() if v}
    return out


